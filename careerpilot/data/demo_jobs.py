def filter_and_rank_jobs(
    target_role: Optional[str] = None,
    user_skills: Optional[List[str]] = None,
    job_type: str = "all",
    remote_only: bool = False,
) -> List[Dict]:
    """Rank demo jobs strictly on skills without CGPA/college tier bias."""
    _ = target_role  # Reserved for future role-affinity weighting
    filtered = [deepcopy(j) for j in DEMO_JOBS]

    if job_type and job_type != "all":
        filtered = [j for j in filtered if j["jobType"].lower() == job_type.lower()]

    if remote_only:
        filtered = [j for j in filtered if j["isRemote"]]

    normalized_user_skills = [s.lower() for s in (user_skills or [])]

    scored: List[Dict] = []
    for job in filtered:
        if job["isScamSuspicious"]:
            scored.append(job)
            continue

        matched_count = sum(
            1
            for s in job["matchedSkills"]
            if any(us in s.lower() or s.lower() in us for us in normalized_user_skills)
        )
        base_match = job.get("matchPercent", 75)
        adjusted = min(98, max(60, base_match + (5 if matched_count > 0 else -5)))
        job["matchPercent"] = adjusted
        scored.append(job)

    scored.sort(key=lambda j: (1 if j["isScamSuspicious"] else 0, -j["matchPercent"]))
    return scored
